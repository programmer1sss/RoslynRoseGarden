#include "Nursery.h" // Підключення оголошення класу Nursery

void Nursery::save(std::ostream& os) const { // Реалізація збереження всіх саджанців у потік
    for (const auto& s : items_) // Проходимо по кожному саджанцю в колекції за константним посиланням
        os << s << '\n';         // Записуємо саженец у потік і додаємо символ переходу на новий рядок
}

void Nursery::load(std::istream& is) { // Реалізація завантаження саджанців із потоку
    items_.clear();          // Очищуємо попередній вміст розсадника
    Seedling temp;           // Тимчасовий об'єкт для зчитування чергового запису
    while (is >> temp) {     // Зчитуємо саджанці з потоку, поки не досягнемо кінця файлу або помилки
        items_.push_back(temp); // Додаємо успішно зчитаний саженец у вектор
    }
}