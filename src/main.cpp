#include <iostream>   
#include <fstream>    
#include <algorithm>  
#include <vector>     
#include "Seedling.h" 
#include "Nursery.h"  
#include "Money.h"    

void printSeparator(const std::string& title) { 
    std::cout << "\n==========================================\n"; 
    std::cout << " " << title << "\n";                              
    std::cout << "==========================================\n";   
}

int main() { // Головна функція — точка входу в програму
    printSeparator("ІНДИВІДУАЛЬНЕ ЗАВДАННЯ: Розсадник рослин"); // Виводимо головний заголовок

    // 1. Створюємо розсадник
    Nursery nursery; // Створюємо порожній об'єкт розсадника
    nursery.add(Seedling("APPLE-1", "Антонівка", 2, 150, Money(125, 00))); // Додаємо яблуню Антонівка
    nursery.add(Seedling("PEAR-2",  "Лісова",   1, 120, Money(95,  50))); // Додаємо грушу Лісова
    nursery.add(Seedling("PLUM-3",  "Угорка",   3, 180, Money(140, 00))); // Додаємо сливу Угорка
    nursery.add(Seedling("APPLE-1", "Антонівка", 2, 150, Money(125, 00))); // Додаємо дублікат першого саджанця
    nursery.add(Seedling("APPLE-1", "Антонівка", 3, 170, Money(135, 00))); // Додаємо дублікат першого саджанця

    std::cout << "Розсадник (" << nursery.size() << " саджанців):\n"; // Виводимо кількість доданих саджанців
    for (std::size_t i = 0; i < nursery.size(); ++i) // Цикл по індексах усіх елементів розсадника
        std::cout << "  " << nursery.at(i) << '\n';  // Виводимо інформацію про кожен саженец

    // 2. Сортування
    std::vector<Seedling> sorted(nursery.items().begin(), nursery.items().end()); // Створюємо копію вектора саджанців
    std::sort(sorted.begin(), sorted.end()); // Сортуємо копію (використовується Seedling::operator<)

    printSeparator("Після сортування (назва → вік → висота)"); // Виводимо заголовок секції сортування
    for (const auto& s : sorted)           // Проходимо по відсортованому вектору
        std::cout << "  " << s << '\n';    // Виводимо відсортовані саджанці

    // 3. Запис у файл
    { // Відкриваємо локальну область видимості для автоматичного закриття файлу (RAII)
        std::ofstream out("nursery.txt"); // Відкриваємо файл nursery.txt для запису
        if (!out) { std::cerr << "Помилка запису!\n"; return 1; } // Якщо файл не відкрився, виводимо помилку і завершуємо програму
        nursery.save(out); // Зберігаємо всі дані розсадника у файл
    } // При виході з блоку деструктор std::ofstream автоматично закриває файл
    std::cout << "\nКаталог збережено в nursery.txt\n"; // Повідомляємо про успішне збереження

    // 4. Читання з файлу
    Nursery restored; // Створюємо новий об'єкт розсадника для відновлення даних
    { // Локальна область видимості для файлового потоку читання
        std::ifstream in("nursery.txt"); // Відкриваємо файл nursery.txt для читання
        if (!in) { std::cerr << "Помилка читання!\n"; return 1; } // Перевіряємо, чи успішно відкрився файл
        restored.load(in); // Завантажуємо саджанці з файлу в об'єкт restored
    } // Файл автоматично закривається
    std::cout << "Каталог відновлено: " << restored.size() << " саджанців\n"; // Виводимо кількість відновлених записів

    // 5. Перевірка безвтратності
    bool ok = (nursery.size() == restored.size()) // Перевіряємо, чи збігається кількість елементів до і після збереження
           && std::equal(nursery.items().begin(), nursery.items().end(), // Поелементно порівнюємо вихідний вектор
                         restored.items().begin());                      // з відновленим вектором (через operator==)
    std::cout << "\nБезвтратний цикл: " << (ok ? "ТАК" : "НІ") << '\n'; // Виводимо результат перевірки цілісності даних

    // 6. Демонстрація операторів Money
    printSeparator("Оператори Money");

    Money m1(125, 50); // 125.50 грн
    Money m2(40, 75);  // 40.75 грн

    // 6.1. Виведення  (operator<<)
    std::cout << "Початкові суми: m1 = " << m1 << ", m2 = " << m2 << '\n';

    // 6.2. Бінарні арифметичні оператори (+, -, *)
    std::cout << "Додавання (m1 + m2):          " << (m1 + m2) << '\n';
    std::cout << "Віднімання (m1 - m2):         " << (m1 - m2) << '\n';
    std::cout << "Множення справа (m1 * 3):     " << (m1 * 3) << '\n';
    std::cout << "Множення зліва (2 * m2):      " << (2 * m2) << '\n';

    // 6.3. Унарний мінус (operator-)
    std::cout << "Унарний мінус (-m2):          " << (-m2) << '\n';

    // 6.4. Складені оператори присвоєння (+=, -=, *=)
    Money acc(100, 0);
    std::cout << "\nАкумулятор acc = " << acc << '\n';
    acc += m2;
    std::cout << "Після acc += m2:              " << acc << '\n';
    acc -= Money(20, 25);
    std::cout << "Після acc -= 20.25:           " << acc << '\n';
    acc *= 2;
    std::cout << "Після acc *= 2:               " << acc << '\n';

    // 6.5. Оператори порівняння (==, !=, <, >, <=, >=)
    std::cout << "\nПорівняння m1 (" << m1 << ") та m2 (" << m2 << "):\n";
    std::cout << std::boolalpha; // Виводити true/false замість 1/0
    std::cout << "  m1 == m2 : " << (m1 == m2) << '\n';
    std::cout << "  m1 != m2 : " << (m1 != m2) << '\n';
    std::cout << "  m1 >  m2 : " << (m1 > m2)  << '\n';
    std::cout << "  m1 <  m2 : " << (m1 < m2)  << '\n';
    std::cout << "  m1 >= m1 : " << (m1 >= m1) << '\n';
    std::cout << "  m2 <= m1 : " << (m2 <= m1) << '\n';

    // 6.6. Підрахунок сумарної вартості каталогу (з основного завдання)
    Money total(0, 0);
    for (const auto& s : nursery.items())
        total += s.getPrice();


    std::cout << "Сумарна вартість усіх саджанців: " << total << '\n'; // Виводимо загальну вартість
    std::cout << "Середня ціна: " << (total * (1.0 / nursery.size())) << '\n'; // Обчислюємо та виводимо середню ціну (примітка: тут double неявно зведеться до int 0)


    return 0; // Успішне завершення програми (код повернення 0)
}